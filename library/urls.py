# ==========================================
# ملف urls.py
# ==========================================
from django.urls import path
from . import views

# توثيق مساحة الأسماء لتسهيل استدعاء الروابط ديناميكياً ضمن واجهات HTML
# مثال الاستدعاء الفعلي: {% url 'library:home' %}
app_name = 'library'

urlpatterns = [
    # ==========================================
    # 1. منظومة المصادقة وإدارة الجلسات
    # ==========================================
    path('register/', views.register, name='register'),
    path('login/', views.login_view, name='login'),
    path('logout/', views.logout_view, name='logout'),

    # ==========================================
    # 2. الواجهات الرئيسية ومحرك البحث الدلالي
    # ==========================================
    # بوابة النظام المركزية واستعراض التوصيات الهجينة
    path('', views.home, name='home'),
    
    # محرك البحث المعزز بالذكاء الاصطناعي وتقنيات توسيع الاستعلام
    path('search/', views.search_view, name='search'),
    
    # واجهة العرض التفصيلية للعناصر المرجعية والكتب المتشابهة
    path('book/<int:book_id>/', views.book_detail, name='book_detail'),

    # ==========================================
    # 3. إدارة الملف الشخصي للطلاب
    # ==========================================
    # مراقبة الأنشطة، التنبيهات، وعرض سحابة الاهتمامات
    path('profile/', views.profile_view, name='profile'),

    # ==========================================
    # 4. لوحات دعم القرار والتحليل الاستراتيجي
    # ==========================================
    # منصة استعراض المؤشرات الحيوية وتحليل فجوة المحتوى (للمشرفين)
    path('analytics/', views.analytics_dashboard, name='analytics'),

    # ==========================================
    # 5. مسارات التحكم بالعمليات والمخزون
    # ==========================================
    # توجيه طلبات الاستعارة الإلكترونية الصادرة عن المستخدم
    path('borrow/<int:book_id>/', views.borrow_request, name='borrow_request'),
    
    # معالجة القرارات الإدارية للمشرف (الموافقة، الرفض، تأكيد الاسترجاع)
    path('transaction/<int:transaction_id>/<str:action>/', views.manage_transaction, name='manage_transaction'),

    # ==========================================
    # 6. منظومة المكتبة الواقعية (التواجد المادي)
    # ==========================================
    # مسار تسجيل توقيت دخول الطالب وبداية نشاطه المكاني
    path('physical/check-in/', views.physical_check_in, name='physical_check_in'),
    
    # مسار تسجيل توقيت الخروج وحساب المدة الإجمالية للبقاء
    path('physical/check-out/<int:visit_id>/', views.physical_check_out, name='physical_check_out'),
]